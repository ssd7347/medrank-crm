-- Numbers of people whose data was erased after they had said no to AI calls (opted out, refused, or marked
-- "Do not call"). Only a SHA-256 hash of the number is kept, so the person cannot be read back from it, but a
-- list imported later cannot make that number callable again.
CREATE TABLE erased_number (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone_hash  VARCHAR(64) NOT NULL,
    erased_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_erased_number UNIQUE (phone_hash)
);
