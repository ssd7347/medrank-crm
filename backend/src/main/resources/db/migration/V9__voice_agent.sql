-- Phase 6: AI voice calling agent (spec 4.29 and section 18). Everything except the live phone call:
-- consent, do-not-disturb checks, versioned scripts, campaigns, calls with transcripts, the tool audit
-- trail, human callbacks and webhook de-duplication. A telephony + voice-AI provider plugs in later.

-- ---------------------------------------------------------------- consent (spec 18.14.2)

-- One row each time consent is given or refused for a phone number. The newest row for a number decides;
-- revoked_at is set the moment someone asks not to be called.
CREATE TABLE contact_consent (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_type        VARCHAR(10)  NOT NULL,
    person_id          BIGINT       NOT NULL,
    phone              VARCHAR(20)  NOT NULL,
    ai_call_consent    BOOLEAN      NOT NULL,
    recording_consent  BOOLEAN      NOT NULL,
    source             VARCHAR(30)  NOT NULL,
    evidence_ref       VARCHAR(500),
    captured_by        BIGINT REFERENCES app_user (id),
    captured_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at         TIMESTAMP WITH TIME ZONE,
    revoke_note        VARCHAR(200)
);
CREATE INDEX ix_consent_phone ON contact_consent (phone);
CREATE INDEX ix_consent_person ON contact_consent (person_type, person_id);

-- Cached do-not-disturb lookups. Only a hash of the number is kept.
CREATE TABLE dnd_check (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone_hash  VARCHAR(64) NOT NULL,
    result      VARCHAR(12) NOT NULL,
    checked_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_dnd_hash ON dnd_check (phone_hash);

-- ---------------------------------------------------------------- scripts (spec 18.11)

-- What the agent is told to do, per call purpose and language. A new version is a new row; campaigns may
-- only use a version an admin has approved.
CREATE TABLE voice_script_template (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purpose        VARCHAR(30)    NOT NULL,
    language       VARCHAR(10)    NOT NULL,
    version        INT            NOT NULL,
    model          VARCHAR(60)    NOT NULL,
    system_prompt  VARCHAR(20000) NOT NULL,
    opening_line   VARCHAR(1000)  NOT NULL,
    approved_by    BIGINT REFERENCES app_user (id),
    approved_at    TIMESTAMP WITH TIME ZONE,
    active         BOOLEAN        NOT NULL DEFAULT FALSE,
    created_by     BIGINT REFERENCES app_user (id),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_voice_script UNIQUE (purpose, language, version)
);

-- ---------------------------------------------------------------- campaigns (spec 18.10)

CREATE TABLE voice_campaign (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(120) NOT NULL,
    purpose         VARCHAR(30)  NOT NULL,
    status          VARCHAR(12)  NOT NULL,
    window_start    TIME         NOT NULL,
    window_end      TIME         NOT NULL,
    max_concurrent  INT          NOT NULL,
    max_attempts    INT          NOT NULL,
    retry_gap_min   INT          NOT NULL,
    -- How far ahead to look for a deadline or a fee due date when picking who to call.
    lookahead_days  INT          NOT NULL,
    branch_id       BIGINT REFERENCES branch (id),
    created_by      BIGINT       NOT NULL REFERENCES app_user (id),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    started_at      TIMESTAMP WITH TIME ZONE,
    finished_at     TIMESTAMP WITH TIME ZONE
);

CREATE TABLE voice_campaign_target (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id      BIGINT      NOT NULL REFERENCES voice_campaign (id),
    student_id       BIGINT REFERENCES student (id),
    lead_id          BIGINT REFERENCES lead (id),
    phone            VARCHAR(20) NOT NULL,
    recipient        VARCHAR(10) NOT NULL,
    status           VARCHAR(14) NOT NULL,
    skip_reason      VARCHAR(30),
    attempts         INT         NOT NULL DEFAULT 0,
    next_attempt_at  TIMESTAMP WITH TIME ZONE,
    last_call_id     UUID,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_voice_target UNIQUE (campaign_id, phone)
);
CREATE INDEX ix_voice_target_status ON voice_campaign_target (campaign_id, status);

-- ---------------------------------------------------------------- calls (spec 18.9)

-- The call id is a random UUID issued by us. The voice platform only ever quotes this id back, and the
-- backend works out whose call it is, so a caller can never ask for someone else's record.
CREATE TABLE voice_call (
    id                  UUID PRIMARY KEY,
    direction           VARCHAR(8)   NOT NULL,
    purpose             VARCHAR(30)  NOT NULL,
    student_id          BIGINT REFERENCES student (id),
    lead_id             BIGINT REFERENCES lead (id),
    phone               VARCHAR(20)  NOT NULL,
    language            VARCHAR(10)  NOT NULL,
    campaign_id         BIGINT REFERENCES voice_campaign (id),
    script_id           BIGINT REFERENCES voice_script_template (id),
    provider            VARCHAR(20)  NOT NULL,
    provider_call_id    VARCHAR(80),
    status              VARCHAR(14)  NOT NULL,
    -- True for calls run from the test console: nothing is saved against the student.
    test_call           BOOLEAN      NOT NULL DEFAULT FALSE,
    recording_allowed   BOOLEAN      NOT NULL DEFAULT FALSE,
    verification_level  INT          NOT NULL DEFAULT 0,
    verify_failures     INT          NOT NULL DEFAULT 0,
    speaker_type        VARCHAR(10),
    outcome             VARCHAR(30),
    outcome_note        VARCHAR(1000),
    handoff_reason      VARCHAR(30),
    started_at          TIMESTAMP WITH TIME ZONE,
    ended_at            TIMESTAMP WITH TIME ZONE,
    duration_sec        INT,
    disconnect_reason   VARCHAR(40),
    recording_ref       VARCHAR(500),
    transcript          VARCHAR(100000),
    summary             VARCHAR(2000),
    flagged_wrong       BOOLEAN      NOT NULL DEFAULT FALSE,
    flag_note           VARCHAR(1000),
    flagged_by          BIGINT REFERENCES app_user (id),
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_voice_provider_call UNIQUE (provider_call_id)
);
CREATE INDEX ix_voice_call_student ON voice_call (student_id, created_at);
CREATE INDEX ix_voice_call_lead ON voice_call (lead_id, created_at);
CREATE INDEX ix_voice_call_phone ON voice_call (phone, created_at);
CREATE INDEX ix_voice_call_created ON voice_call (created_at);

-- One row per tool the agent used during a call. Arguments are stored only as a hash.
CREATE TABLE voice_tool_audit (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    call_id     UUID        NOT NULL REFERENCES voice_call (id),
    tool        VARCHAR(40) NOT NULL,
    args_hash   VARCHAR(64),
    status      VARCHAR(24) NOT NULL,
    latency_ms  INT,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_voice_tool_call ON voice_tool_audit (call_id);
CREATE INDEX ix_voice_tool_created ON voice_tool_audit (created_at);

-- ---------------------------------------------------------------- human callbacks (spec 18.13)

CREATE TABLE callback_request (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id           BIGINT REFERENCES student (id),
    lead_id              BIGINT REFERENCES lead (id),
    voice_call_id        UUID REFERENCES voice_call (id),
    phone                VARCHAR(20),
    reason               VARCHAR(40)  NOT NULL,
    preferred_time_text  VARCHAR(200),
    summary              VARCHAR(2000),
    priority             VARCHAR(10)  NOT NULL,
    status               VARCHAR(12)  NOT NULL,
    assigned_to          BIGINT REFERENCES app_user (id),
    due_at               TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    done_at              TIMESTAMP WITH TIME ZONE,
    done_by              BIGINT REFERENCES app_user (id),
    done_note            VARCHAR(1000)
);
CREATE INDEX ix_callback_status ON callback_request (status, due_at);

-- ---------------------------------------------------------------- webhooks and the kill switch

-- A provider may deliver the same event twice; the unique key makes the second one a no-op.
CREATE TABLE voice_webhook_event (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_call_id  VARCHAR(80) NOT NULL,
    event_type        VARCHAR(30) NOT NULL,
    received_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_voice_webhook UNIQUE (provider_call_id, event_type)
);

-- Single row. paused = the "Pause all" switch: no call is placed while it is on.
CREATE TABLE voice_setting (
    id         INT PRIMARY KEY,
    paused     BOOLEAN NOT NULL,
    paused_by  BIGINT REFERENCES app_user (id),
    paused_at  TIMESTAMP WITH TIME ZONE
);
INSERT INTO voice_setting (id, paused) VALUES (1, FALSE);

