-- Customisation base: stages each customer names themselves, a logo, login-page wording, and which
-- industry starter pack was loaded.

-- The stages a contact moves through. contact.status holds a stage_key. Built-in stages are used by the AI
-- agent (it moves people to Contacted / Interested / Not interested / Do not call), so they can be renamed,
-- recoloured and reordered but not deleted. category groups stages for reports: OPEN, WON or LOST.
CREATE TABLE contact_stage (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage_key   VARCHAR(20)  NOT NULL,
    label       VARCHAR(40)  NOT NULL,
    color       VARCHAR(7)   NOT NULL,
    category    VARCHAR(10)  NOT NULL,
    sort_order  INT          NOT NULL,
    built_in    BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_stage_key UNIQUE (stage_key)
);
