-- AI Call CRM: contacts imported from spreadsheets, called by an English-speaking AI agent, with people
-- taking over when needed. One installation per customer company.

-- ---------------------------------------------------------------- company settings (white-label)

-- Single row. Everything a customer sees as "their" brand lives here, so a new installation needs no code change.
CREATE TABLE app_setting (
    id             INT PRIMARY KEY,
    company_name   VARCHAR(120) NOT NULL,
    agent_name     VARCHAR(40)  NOT NULL,
    brand_color    VARCHAR(7)   NOT NULL,
    support_phone  VARCHAR(20),
    contact_label  VARCHAR(30)  NOT NULL,
    updated_by     BIGINT,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL
);
