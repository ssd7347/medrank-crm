CREATE INDEX ix_audit_entity ON audit_log (entity_type, entity_id);

-- ---------------------------------------------------------------- contacts

-- The extra columns a customer's spreadsheets carry (amount due, due date, customer ID, plan, ...).
-- agent_access decides what the AI may say: NONE, AFTER_VERIFY (only once the caller has proved who they
-- are) or ANYONE. verify_with marks a field the caller can be asked to confirm, such as a customer ID.
CREATE TABLE field_definition (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    field_key     VARCHAR(40)  NOT NULL,
    label         VARCHAR(80)  NOT NULL,
    field_type    VARCHAR(10)  NOT NULL,
    agent_access  VARCHAR(12)  NOT NULL,
    verify_with   BOOLEAN      NOT NULL DEFAULT FALSE,
    sort_order    INT          NOT NULL DEFAULT 100,
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_field_key UNIQUE (field_key)
);

-- One spreadsheet upload: what was in it, how its columns were matched, and what happened to each row.
CREATE TABLE import_batch (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_name     VARCHAR(200)  NOT NULL,
    rows_total    INT           NOT NULL,
    created_count INT           NOT NULL,
    updated_count INT           NOT NULL,
    skipped_count INT           NOT NULL,
    problems      VARCHAR(20000),
    mapping       VARCHAR(4000),
    created_by    BIGINT REFERENCES app_user (id),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE contact (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name        VARCHAR(120)   NOT NULL,
    phone            VARCHAR(20)    NOT NULL,
    alt_phone        VARCHAR(20),
    email            VARCHAR(160),
    status           VARCHAR(20)    NOT NULL,
    source           VARCHAR(60),
    notes            VARCHAR(2000),
    -- Values of the custom fields, as a JSON object keyed by field_definition.field_key.
    fields           VARCHAR(20000),
    assigned_to      BIGINT REFERENCES app_user (id),
    branch_id        BIGINT REFERENCES branch (id),
    import_batch_id  BIGINT REFERENCES import_batch (id),
    created_by       BIGINT REFERENCES app_user (id),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_contact_phone UNIQUE (phone)
);
CREATE INDEX ix_contact_status ON contact (status);
CREATE INDEX ix_contact_assigned ON contact (assigned_to);
CREATE INDEX ix_contact_batch ON contact (import_batch_id);

CREATE TABLE contact_activity (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contact_id  BIGINT       NOT NULL REFERENCES contact (id),
    type        VARCHAR(20)  NOT NULL,
    outcome     VARCHAR(120),
    notes       VARCHAR(2000),
    created_by  BIGINT REFERENCES app_user (id),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_contact_activity_contact ON contact_activity (contact_id);

CREATE TABLE follow_up (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contact_id    BIGINT       NOT NULL REFERENCES contact (id),
    assigned_to   BIGINT       NOT NULL REFERENCES app_user (id),
    due_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    purpose       VARCHAR(200),
    completed_at  TIMESTAMP WITH TIME ZONE,
    completed_by  BIGINT REFERENCES app_user (id),
    created_by    BIGINT REFERENCES app_user (id),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_follow_up_assignee ON follow_up (assigned_to, completed_at, due_at);

-- Every call to or from a contact, by a person or by the AI agent (provider = AI_AGENT, linked to its transcript).
CREATE TABLE call_log (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contact_id        BIGINT      NOT NULL REFERENCES contact (id),
    phone             VARCHAR(20) NOT NULL,
    direction         VARCHAR(10) NOT NULL,
    outcome           VARCHAR(20) NOT NULL,
