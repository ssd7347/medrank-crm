-- The exact text the family agreed to is copied here, so later template edits never change what was signed.
CREATE TABLE student_agreement (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id         BIGINT        NOT NULL REFERENCES student (id),
    template_id        BIGINT REFERENCES agreement_template (id),
    kind               VARCHAR(30)   NOT NULL,
    title              VARCHAR(200)  NOT NULL,
    body               VARCHAR(20000) NOT NULL,
    body_sha256        VARCHAR(64)   NOT NULL,
    status             VARCHAR(20)   NOT NULL,
    sign_method        VARCHAR(30),
    signer_name        VARCHAR(120),
    signer_relation    VARCHAR(20),
    signed_at          TIMESTAMP WITH TIME ZONE,
    signer_ip          VARCHAR(45),
    portal_account_id  BIGINT REFERENCES portal_account (id),
    provider_ref       VARCHAR(120),
    issued_by          BIGINT REFERENCES app_user (id),
    issued_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    recorded_by        BIGINT REFERENCES app_user (id)
);
CREATE INDEX ix_student_agreement_student ON student_agreement (student_id);

