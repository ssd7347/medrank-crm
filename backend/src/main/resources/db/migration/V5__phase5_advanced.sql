-- ---------------------------------------------------------------- education loans (spec 4.26)

-- Lenders the firm refers students to. Rates shown are reference-only; the firm does not underwrite.
CREATE TABLE loan_partner (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(120) NOT NULL,
    interest_info  VARCHAR(200),
    max_amount     NUMERIC(12, 2),
    eligibility    VARCHAR(1000),
    contact_name   VARCHAR(120),
    contact_phone  VARCHAR(20),
    active         BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE loan_application (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id         BIGINT         NOT NULL REFERENCES student (id),
    partner_id         BIGINT         NOT NULL REFERENCES loan_partner (id),
    amount_requested   NUMERIC(12, 2) NOT NULL,
    amount_sanctioned  NUMERIC(12, 2),
    status             VARCHAR(20)    NOT NULL,
    -- The date the money must be available by, normally the college reporting deadline.
    needed_by          DATE,
    applied_on         DATE,
    decided_on         DATE,
    reference_no       VARCHAR(60),
    co_applicant       VARCHAR(120),
    notes              VARCHAR(2000),
    handled_by         BIGINT REFERENCES app_user (id),
    created_by         BIGINT REFERENCES app_user (id),
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_loan_amount CHECK (amount_requested > 0)
);
CREATE INDEX ix_loan_application_student ON loan_application (student_id);
CREATE INDEX ix_loan_application_status ON loan_application (status);

-- ---------------------------------------------------------------- counselling sessions (spec 4.19)

CREATE TABLE counselling_session (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id         BIGINT       NOT NULL REFERENCES student (id),
    host_id            BIGINT       NOT NULL REFERENCES app_user (id),
    mode               VARCHAR(20)  NOT NULL,
    scheduled_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    duration_minutes   INT          NOT NULL,
    topic              VARCHAR(200) NOT NULL,
    meeting_url        VARCHAR(500),
    status             VARCHAR(20)  NOT NULL,
    notes              VARCHAR(4000),
    recording_consent  BOOLEAN      NOT NULL DEFAULT FALSE,
    recording_url      VARCHAR(500),
    created_by         BIGINT REFERENCES app_user (id),
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_session_student ON counselling_session (student_id);
CREATE INDEX ix_session_host_time ON counselling_session (host_id, scheduled_at);

-- ---------------------------------------------------------------- call log (spec 4.21)

-- One row per call attempt to a lead or student. provider_* columns are filled by a telephony provider
-- (Exotel/Knowlarity) once connected; until then staff dial from their phone and record the outcome.
CREATE TABLE call_log (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lead_id           BIGINT REFERENCES lead (id),
    student_id        BIGINT REFERENCES student (id),
    phone             VARCHAR(20) NOT NULL,
    direction         VARCHAR(10) NOT NULL,
    outcome           VARCHAR(20) NOT NULL,
    duration_seconds  INT,
    notes             VARCHAR(2000),
    provider          VARCHAR(30),
    provider_call_id  VARCHAR(80),
    recording_url     VARCHAR(500),
    called_by         BIGINT REFERENCES app_user (id),
    called_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_call_log_target CHECK (lead_id IS NOT NULL OR student_id IS NOT NULL)
);
CREATE INDEX ix_call_log_lead ON call_log (lead_id);
CREATE INDEX ix_call_log_student ON call_log (student_id);
CREATE INDEX ix_call_log_caller_time ON call_log (called_by, called_at);

-- ---------------------------------------------------------------- agreements & consent (spec 4.20)

CREATE TABLE agreement_template (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind        VARCHAR(30)   NOT NULL,
    title       VARCHAR(200)  NOT NULL,
    body        VARCHAR(20000) NOT NULL,
    active      BOOLEAN       NOT NULL DEFAULT TRUE,
