-- ---------------------------------------------------------------- documents (spec 4.7)

-- Checklist items. applies_when decides which students need it (configurable, spec 4.7).
CREATE TABLE document_type (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code             VARCHAR(40)  NOT NULL,
    name             VARCHAR(120) NOT NULL,
    applies_when     VARCHAR(20)  NOT NULL,
    requires_expiry  BOOLEAN      NOT NULL DEFAULT FALSE,
    sort_order       INT          NOT NULL DEFAULT 100,
    active           BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_document_type_code UNIQUE (code)
);

CREATE TABLE student_document (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id        BIGINT       NOT NULL REFERENCES student (id),
    document_type_id  BIGINT       NOT NULL REFERENCES document_type (id),
    status            VARCHAR(20)  NOT NULL,
    valid_until       DATE,
    notes             VARCHAR(500),
    verified_by       BIGINT REFERENCES app_user (id),
    verified_at       TIMESTAMP WITH TIME ZONE,
    updated_by        BIGINT REFERENCES app_user (id),
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_student_document UNIQUE (student_id, document_type_id)
);

-- Uploaded scans. Every upload is kept (versions); the newest is current.
CREATE TABLE document_file (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_document_id  BIGINT        NOT NULL REFERENCES student_document (id),
    storage_key          VARCHAR(200)  NOT NULL,
    original_name        VARCHAR(200)  NOT NULL,
    content_type         VARCHAR(60)   NOT NULL,
    size_bytes           BIGINT        NOT NULL,
    sha256               VARCHAR(64)   NOT NULL,
    uploaded_by          BIGINT REFERENCES app_user (id),
    uploaded_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_document_file_key UNIQUE (storage_key)
);
CREATE INDEX ix_document_file_doc ON document_file (student_document_id);

